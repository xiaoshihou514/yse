pub const BRIDGE_RS: &str = r#"// Generated by gansi new. The Rust side of the app:
// a small QObject that owns the counter state.
use cxx_qt::CxxQtType;
use std::pin::Pin;

#[cxx_qt::bridge(namespace = "{{name_snake}}")]
pub mod qobject {
    #[namespace = ""]
    unsafe extern "C++" {
        include!("{{name}}/src/spike.h");

        /// Run the application; blocks in the Qt event loop.
        fn run_app() -> i32;
    }

    extern "RustQt" {
        #[qobject]
        #[qproperty(u32, count)]
        type Counter = super::CounterRust;

        #[qinvokable]
        #[cxx_name = "incrementCount"]
        fn increment_count(self: Pin<&mut Self>);
    }
}

pub struct CounterRust {
    pub count: u32,
}

impl Default for CounterRust {
    fn default() -> Self {
        Self { count: 0 }
    }
}

impl qobject::Counter {
    pub fn increment_count(mut self: Pin<&mut Self>) {
        let next = self.as_mut().rust_mut().count + 1;
        self.as_mut().set_count(next);
    }
}
"#;

