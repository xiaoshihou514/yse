pub const SPIKE_CPP: &str = r#"// Generated by gansi new. The C++ shim owns the raw
// Qt Widgets surface; Rust owns the reactive state.

#include "{{name}}/src/spike.h"

#include <QApplication>
#include <QLabel>
#include <QPushButton>
#include <QTimer>
#include <QVBoxLayout>
#include <QWidget>

#include "{{name}}/src/bridge.cxxqt.h"

int run_app() noexcept
{
  int argc = 1;
  static const char arg0[] = "{{name}}";
  char* argv[] = { const_cast<char*>(arg0), nullptr };
  QApplication app(argc, argv);

  QWidget window;
  window.setWindowTitle(QStringLiteral("{{title}}"));
  window.resize(320, 140);
  auto* layout = new QVBoxLayout(&window);
  auto* label = new QLabel(QStringLiteral("Count: 0"), &window);
  auto* button = new QPushButton(QStringLiteral("Increment"), &window);
  layout->addWidget(label);
  layout->addWidget(button);

  {{name_snake}}::Counter counter(&window);
  QObject::connect(button, &QPushButton::clicked, &counter, [&counter] {
    counter.incrementCount();
  });
  QObject::connect(&counter, &{{name_snake}}::Counter::countChanged, &window, [label, &counter] {
    label->setText(
      QStringLiteral("Count: %1").arg(static_cast<qlonglong>(counter.getCount())));
  });

  window.show();

  if (qEnvironmentVariableIsSet("YSE_SMOKE")) {
    QTimer::singleShot(100, &app, [&] { button->click(); });
    QTimer::singleShot(300, &app, [&] { app.quit(); });
  }

  return app.exec();
}
"#;

